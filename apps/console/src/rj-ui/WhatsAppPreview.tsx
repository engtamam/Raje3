// ── THE FLOW SCREEN RENDERER — the real generic engine. Walks `layout.children`, switches on
// `type`, keeps per-field answers in local state, and advances via `routing_model` on Footer tap.

interface FieldValue {
  [name: string]: string | string[];
}

function evalVisible(v: boolean | string | undefined): boolean {
  if (v === undefined) return true;
  if (typeof v === 'boolean') return v;
  // `${data.show_x}` bindings — a preview has no live `data` beyond what the screen ships with,
  // so an unresolved binding defaults to visible rather than silently hiding real content.
  return true;
}

function FlowComponentView({
  node, values, onChange,
}: {
  node: FlowComponent;
  values: FieldValue;
  onChange: (name: string, value: string | string[]) => void;
}) {
  if (!evalVisible(node.visible)) return null;

  switch (node.type) {
    case 'Form':
      return (
        <div className="flex flex-col gap-3">
          {(node.children ?? []).map((c, i) => (
            <FlowComponentView key={i} node={c} values={values} onChange={onChange} />
          ))}
        </div>
      );
    case 'TextHeading':
      return <h3 className="text-base font-bold leading-snug text-[#111b21]">{node.text}</h3>;
    case 'TextSubheading':
      return <h4 className="text-sm font-semibold leading-snug text-[#111b21]">{node.text}</h4>;
    case 'TextBody':
      return <p className="text-sm leading-relaxed text-[#3b4a54]">{node.text}</p>;
    case 'TextCaption':
      return <p className="text-xs leading-relaxed text-[#667781]">{node.text}</p>;
    case 'RichText':
      return <div className="text-sm leading-relaxed text-[#3b4a54] whitespace-pre-wrap">{node.text}</div>;
    case 'Image':
      return (
        <div className="flex h-28 w-full items-center justify-center rounded-lg bg-black/5 text-[#667781]">
          <ImageIcon size={20} aria-hidden />
        </div>
      );
    case 'RadioButtonsGroup':
    case 'Dropdown': {
      const name = node.name ?? 'selection';
      const current = values[name];
      return (
        <fieldset className="flex flex-col gap-2">
          {node.label ? <legend className="mb-0.5 text-xs font-semibold text-[#3b4a54]">{node.label}</legend> : null}
          <div className="flex flex-col overflow-hidden rounded-lg border border-black/10 bg-white">
            {(node['data-source'] ?? []).map((opt, i) => (
              <label
                key={opt.id}
                className={cn(
                  'flex cursor-pointer items-start gap-2.5 px-3 py-2.5 text-sm text-[#111b21] transition hover:bg-black/[0.03]',
                  i > 0 ? 'border-t border-black/5' : '',
                )}
              >
                <input
                  type="radio"
                  name={name}
                  className="mt-0.5 accent-[#25D366]"
                  checked={current === opt.id}
                  onChange={() => onChange(name, opt.id)}
                />
                <span className="flex-1">
                  <span className="block font-medium">{opt.title}</span>
                  {opt.description ? <span className="block text-xs text-[#667781]">{opt.description}</span> : null}
                </span>
              </label>
            ))}
          </div>
        </fieldset>
      );
    }
    case 'CheckboxGroup': {
      const name = node.name ?? 'selection';
      const current = Array.isArray(values[name]) ? (values[name] as string[]) : [];
      const toggle = (id: string) => {
        const next = current.includes(id) ? current.filter((x) => x !== id) : [...current, id];
        onChange(name, next);
      };
      return (
        <fieldset className="flex flex-col gap-2">
          {node.label ? <legend className="mb-0.5 text-xs font-semibold text-[#3b4a54]">{node.label}</legend> : null}
          <div className="flex flex-col overflow-hidden rounded-lg border border-black/10 bg-white">
            {(node['data-source'] ?? []).map((opt, i) => (
              <label
                key={opt.id}
                className={cn(
                  'flex cursor-pointer items-start gap-2.5 px-3 py-2.5 text-sm text-[#111b21] transition hover:bg-black/[0.03]',
                  i > 0 ? 'border-t border-black/5' : '',
                )}
              >
                <input
                  type="checkbox"
                  className="mt-0.5 accent-[#25D366]"
                  checked={current.includes(opt.id)}
                  onChange={() => toggle(opt.id)}
                />
                <span className="flex-1">
                  <span className="block font-medium">{opt.title}</span>
                  {opt.description ? <span className="block text-xs text-[#667781]">{opt.description}</span> : null}
                </span>
              </label>
            ))}
          </div>
        </fieldset>
      );
    }
    case 'TextInput':
    case 'TextArea': {
      const name = node.name ?? 'input_value';
      const current = typeof values[name] === 'string' ? (values[name] as string) : '';
      const Tag = node.type === 'TextArea' ? 'textarea' : 'input';
      return (
        <label className="flex flex-col gap-1">
          {node.label ? <span className="text-xs font-semibold text-[#3b4a54]">{node.label}</span> : null}
          <Tag
            className="rounded-lg border border-black/10 bg-white px-3 py-2 text-sm text-[#111b21] outline-none focus:border-[#25D366]"
            placeholder={node.label ?? ''}
            value={current}
            maxLength={node['max-length'] as number | undefined}
            rows={node.type === 'TextArea' ? 3 : undefined}
            onChange={(e) => onChange(name, e.target.value)}
          />
        </label>
      );
    }
    case 'OptIn': {
      const name = node.name ?? 'opt_in';
      const current = values[name] === 'true';
      return (
        <label className="flex cursor-pointer items-start gap-2.5 text-sm text-[#111b21]">
          <input
            type="checkbox"
            className="mt-0.5 accent-[#25D366]"
            checked={current}
            onChange={(e) => onChange(name, e.target.checked ? 'true' : 'false')}
          />
          <span>{node.label}</span>
        </label>
      );
    }
    case 'CalendarPicker':
      return (
        <label className="flex flex-col gap-1">
          {node.label ? <span className="text-xs font-semibold text-[#3b4a54]">{node.label}</span> : null}
          <input
            type="date"
            className="rounded-lg border border-black/10 bg-white px-3 py-2 text-sm text-[#111b21] outline-none focus:border-[#25D366]"
            onChange={(e) => onChange(node.name ?? 'date', e.target.value)}
          />
        </label>
      );
    case 'Footer':
      // Rendered by `FlowScreenCard` itself (it needs the whole screen's navigation context),
      // never here — kept out of the switch so a Footer nested oddly inside a Form still no-ops
      // instead of drawing a second, disconnected button.
      return null;
    default:
      return null;
  }
}

function footerOf(children: FlowComponent[]): FlowComponent | undefined {
  return children.find((c) => c.type === 'Footer') ?? children.flatMap((c) => c.children ?? []).find((c) => c.type === 'Footer');
}

function FlowScreenCard({
  screen, onAdvance, onComplete,
}: {
  screen: FlowScreen;
  onAdvance: () => void;
  onComplete: () => void;
}) {
  const [values, setValues] = useState<FieldValue>({});
  const footer = footerOf(screen.layout.children);
  const handleChange = (name: string, value: string | string[]) =>
    setValues((v) => ({ ...v, [name]: value }));

  return (
    <div className="flex w-[300px] flex-col gap-3 self-center rounded-xl border border-black/10 bg-white p-4 shadow-md">
      {screen.title ? (
        <p className="text-[11px] font-semibold uppercase tracking-wide text-[#667781]">{screen.title}</p>
      ) : null}
      {screen.layout.children.map((c, i) => (
        <FlowComponentView key={i} node={c} values={values} onChange={handleChange} />
      ))}
      {footer ? (
        <button
          type="button"
          onClick={() => (screen.terminal ? onComplete() : onAdvance())}
          className="mt-1 w-full rounded-lg bg-[#25D366] px-4 py-2.5 text-sm font-semibold text-white shadow-sm transition hover:brightness-95"
        >
          {footer.label}
        </button>
      ) : null}
    </div>
  );
}

export function WaFlowScreens({ flow, onDone }: { flow: FlowJson; onDone: () => void }) {
  const [screenId, setScreenId] = useState(flow.screens[0]?.id ?? '');
  const screen = useMemo(() => flow.screens.find((s) => s.id === screenId), [flow, screenId]);
  if (!screen) return null;

  const advance = () => {
    const next = flow.routing_model[screen.id]?.[0];
    if (next) setScreenId(next);
    else onDone();
  };

  return <FlowScreenCard screen={screen} onAdvance={advance} onComplete={onDone} />;
}

// ── THE CAROUSEL — Meta's own layout: an intro text bubble, then a swipeable row of cards, each
// its own image + body + button, NEVER a scroll-list of a dozen thumbnails (§16's own note on
// MAX_CAROUSEL_CARDS: "a customer scrolling ten cards on a small screen is noise" — the same
// reasoning that keeps this preview to one full card at a time, a peek of the next, not a grid).
//
// NATIVE SCROLL-SNAP FOR THE SWIPE ITSELF, arrow buttons for a mouse user who never thinks to
// drag — same "touch does the real thing, arrows are the fallback" split TicketCarousel.tsx's own
// header already settled, but via CSS scroll-snap here rather than pointer-event math: a real
// finger drag on a touch screen is native browser behaviour this way, not a reimplementation of
// it, and a horizontal `overflow-x-auto` needs no RTL-mirroring trick at all (unlike a
// `translateX`-driven track) because the browser's own scroll direction already follows `dir`.
function WaCarouselCardView({ card }: { card: WaCarouselCard }) {
  return (
    <div className="w-[220px] shrink-0 snap-center overflow-hidden rounded-xl border border-black/10 bg-white shadow-sm">
      <div className="flex h-32 w-full items-center justify-center bg-black/5 text-[#667781]">
        {card.imageUrl ? (
          <img src={card.imageUrl} alt={card.name} className="h-full w-full object-cover" />
        ) : (
          <ImageIcon size={22} aria-hidden />
        )}
      </div>
      <div className="flex flex-col gap-1 p-2.5">
        <p className="text-sm font-medium leading-snug text-[#111b21]">
          {card.name} — {riyalsLabel(card.priceMinor)}
        </p>
      </div>
      <button type="button" disabled
             className="w-full border-t border-black/5 px-3 py-2 text-center text-sm font-medium text-[#00A5F4]">
        {card.buttonLabel}
      </button>
    </div>
  );
}

export function WaCarousel({ intro, cards }: { intro?: string; cards: WaCarouselCard[] }) {
  const trackRef = useRef<HTMLDivElement | null>(null);
  const scrollBy = (dir: 1 | -1) => {
    const el = trackRef.current;
    if (!el) return;
    // `direction: rtl` on the scroll container means the browser's OWN idea of "forward" is
    // already mirrored — a plain positive scrollLeft delta moves toward the NEXT card exactly the
    // way the left arrow (ChevronLeft, "the next one in reading order") should, with no sign flip
    // to hand-derive.
    el.scrollBy({ left: dir * 236, behavior: 'smooth' });
  };
  return (
    <div className="flex w-full flex-col items-end gap-2 self-end">
      {intro ? <WaBubble text={intro} /> : null}
      <div className="relative w-full">
        <div ref={trackRef} dir="rtl"
            className="flex w-full snap-x snap-mandatory gap-2 overflow-x-auto scroll-smooth pb-1"
            style={{ scrollbarWidth: 'none' }}>
          {cards.map((c) => <WaCarouselCardView key={c.id} card={c} />)}
        </div>
        {cards.length > 1 ? (
          <>
            <button type="button" aria-label="البطاقة التالية" onClick={() => scrollBy(1)}
                   className="absolute -start-2 top-1/2 grid h-7 w-7 -translate-y-1/2 place-items-center rounded-full bg-white text-[#111b21] shadow-md">
              <ChevronLeft size={14} aria-hidden />
            </button>
            <button type="button" aria-label="البطاقة السابقة" onClick={() => scrollBy(-1)}
                   className="absolute -end-2 top-1/2 grid h-7 w-7 -translate-y-1/2 place-items-center rounded-full bg-white text-[#111b21] shadow-md">
              <ChevronRight size={14} aria-hidden />
            </button>
          </>
        ) : null}
      </div>
    </div>
  );
}

// ── THE TOP-LEVEL, COMPOSED PIECE every screen actually imports. Data in, phone-realistic and
// interactive preview out — the "thin configuration per Flow" the engine was built to support:
// a caller supplies `data` and (if there's a Flow button) `fetchFlowJson`, nothing else.

export function WhatsAppTemplatePreview({
  data, fetchFlowJson, contactName,
}: {
  data: WaTemplateData;
  /** Injected, never hardcoded — the admin screen calls the `platform.operations`-gated route,
   *  the shop screen calls the `operations.read` one; this component knows neither URL nor auth. */
  fetchFlowJson?: (flowName: string) => Promise<FlowJson>;
  contactName?: string;
}) {
  const [flow, setFlow] = useState<FlowJson | null>(null);
  const [error, setError] = useState('');
  const [loading, setLoading] = useState(false);
  const [open, setOpen] = useState(false);

  const text = fillPlaceholders(data.body, data.examples);
  const buttons: Array<{ label: string; kind: 'flow' | 'url' | 'reply' }> = [];
  if (data.flowButton) buttons.push({ label: data.flowButton.text || 'فتح', kind: 'flow' });
  if (data.urlButton) buttons.push({ label: data.urlButton.text || 'رابط', kind: 'url' });
  if (data.replyButton) buttons.push({ label: data.replyButton.text || 'رد', kind: 'reply' });

  useEffect(() => {
    // Reset the live walkthrough whenever the underlying data changes (a new template selected),
    // rather than showing a stale Flow under a different message.
    setFlow(null);
    setOpen(false);
    setError('');
  }, [data.flowButton?.flowName, data.body]);

  async function openFlow() {
    if (!data.flowButton || !fetchFlowJson) return;
    setOpen(true);
    if (flow) return;
    setLoading(true);
    setError('');
    try {
      const j = await fetchFlowJson(data.flowButton.flowName);
      setFlow(j);
    } catch (e) {
      setError(e instanceof Error ? e.message : 'تعذّر جلب الفلو.');
    } finally {
      setLoading(false);
    }
  }

  return (
    <WaPhoneFrame contactName={contactName}>
      {data.carousel ? (
        <WaCarousel intro={text} cards={data.carousel} />
      ) : !open ? (
        <WaBubble
          text={text}
          buttons={buttons}
          onPressButton={(i) => {
            const b = buttons[i];
            if (b.kind === 'flow') void openFlow();
          }}
        />
      ) : loading ? (
        <div className="flex w-[300px] flex-col gap-2 self-center rounded-xl border border-black/10 bg-white p-4 shadow-md">
          <Skeleton className="h-4 w-2/3" />
          <Skeleton className="h-3 w-full" />
          <Skeleton className="h-3 w-full" />
          <Skeleton className="h-8 w-full" />
        </div>
      ) : error ? (
        <div className="flex w-[300px] flex-col gap-2 self-center rounded-xl border border-danger-soft bg-white p-4 text-center shadow-md">
          <p className="text-sm text-danger-on-soft">{error}</p>
          <button type="button" onClick={() => setOpen(false)} className="text-xs text-accent underline">
            رجوع للرسالة
          </button>
        </div>
      ) : flow ? (
        <WaFlowScreens flow={flow} onDone={() => setOpen(false)} />
      ) : null}
    </WaPhoneFrame>
  );
}
