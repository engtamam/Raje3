/** ONE CARD OF A REAL WHATSAPP CAROUSEL SEND — the exact shape
 *  `app/ports/catalog_provider.py::CatalogCard` carries in production (id/kind/name/price_minor/
 *  image_url), plus the one piece of template text every card shares
 *  (`operations/data/templates.seed.json`'s own `wa_catalog_carousel` row: body
 *  "{{1}} — {{2}}", button "احجز الآن") — never invented sample copy. */
export interface WaCarouselCard {
  id: string;
  kind: 'service' | 'package';
  name: string;
  priceMinor: number;
  imageUrl?: string;
  buttonLabel: string;
}

export interface WaTemplateData {
  body: string;
  /** `{{1}}`/`{{2}}` filled with real example values, so the bubble reads like a real message
   *  rather than showing literal placeholders. */
  examples?: string[];
  flowButton?: WaFlowButton;
  /** A plain URL button, the template's other possible shape. */
  urlButton?: { text: string; url?: string };
  /** A flat QUICK_REPLY button — no Flow, no URL, just a tap that comes back as a reply webhook
   *  (campaigns' own single-item button, core/shape.py). Meta renders it identically to a URL
   *  button except for the icon; drawn with none here, matching how WhatsApp itself shows a
   *  quick-reply row (no external-link glyph, since it never leaves the chat). */
  replyButton?: { text: string };
  /** THE THIRD SHAPE A SEND CAN TAKE — present only for a carousel template
   *  (`wa_catalog_carousel`). Mutually exclusive with `flowButton`/`urlButton` in practice (Meta's
   *  own template types never combine them), rendered as `WaCarousel` instead of a single
   *  bubble+button row. */
  carousel?: WaCarouselCard[];
}

function fillPlaceholders(body: string, examples?: string[]): string {
  if (!examples || examples.length === 0) return body;
  return body.replace(/\{\{(\d+)\}\}/g, (_m, n) => examples[Number(n) - 1] ?? `{{${n}}}`);
}

