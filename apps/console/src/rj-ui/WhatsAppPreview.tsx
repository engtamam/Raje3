// ── THE REAL FLOW JSON SHAPE, as generated by `flow_json.py` / hand-authored under `flows.py` ──

export interface FlowComponent {
  type: string;
  name?: string;
  label?: string;
  text?: string;
  required?: boolean;
  'input-type'?: string;
  'max-length'?: number;
  'min-selected-items'?: number;
  'data-source'?: Array<{ id: string; title: string; description?: string }>;
  'on-click-action'?: { name: string; next?: { name: string }; payload?: Record<string, unknown> };
  children?: FlowComponent[];
  visible?: boolean | string;
  [key: string]: unknown;
}

export interface FlowScreen {
  id: string;
  title?: string;
  terminal?: boolean;
  success?: boolean;
  data?: Record<string, unknown>;
  layout: { type: string; children: FlowComponent[] };
}

export interface FlowJson {
  version: string;
  data_api_version?: string;
  routing_model: Record<string, string[]>;
  screens: FlowScreen[];
}

