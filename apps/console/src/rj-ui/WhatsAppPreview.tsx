/**
 * The WhatsApp preview ENGINE — component #7, and the only one in this kit that renders another
 * system's own document format rather than our own data.
 *
 * WHY AN ENGINE AND NOT ONE PREVIEW PER TEMPLATE. A template screen that hand-draws "the renewal
 * Flow's three screens" would need a second hand-drawn copy the day a booking-Flow preview is
 * asked for, and a third for delivery, and so on — drift guaranteed, because nothing forces the
 * hand-drawn copy to track what the real Flow actually renders. This file instead renders THE
 * REAL FLOW JSON — the exact document `flow_json.py` generates and Meta itself parses, fetched
 * through `WhatsAppTemplatePreview`'s injected `fetchFlowJson` — so any Flow this product ever
 * registers (booking, visit, delivery, loyalty, a fifth one next year) previews correctly the
 * moment it is registered, with zero new preview code. A screen that wants one just supplies data:
 * the message body, the variables, and — if the template carries a Flow button — a fetcher.
 *
 * SCOPE, ON PURPOSE. This is a PREVIEW, not a second implementation of the Flow protocol: no
 * RSA/AES envelope, no session id, no server round-trip on each screen (`data_exchange` is
 * simulated locally by walking `routing_model`). What it renders is pixel-real; what happens when
 * you tap through it is a faithful walkthrough, not a live booking. `flow_dispatch.py` still owns
 * the one wire that actually talks to Meta.
 *
 * COVERS THE COMPONENT VOCABULARY THIS CODEBASE ACTUALLY EMITS (see `flow_json.py` and the
 * hand-authored `SUBSCRIPTION_RENEWAL_FLOW_JSON`/`rating-flow.json`/`report-flow.json`):
 * TextHeading, TextSubheading, TextBody, TextCaption, RichText, Form, RadioButtonsGroup,
 * CheckboxGroup, Dropdown, TextInput, TextArea, OptIn, CalendarPicker, Image, Footer. An unknown
 * component type renders nothing rather than breaking the screen — a Flow using a component this
 * engine has not learned yet degrades to "screen looks sparse," never "click and it explodes."
 */
