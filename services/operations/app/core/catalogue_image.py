"""One product photo per service or package, held in `ObjectStore` — never a URL, never a second
storage system.

WHY NOT THE LOGO'S OWN INLINE-BASE64 PATTERN. `AccountPanes.tsx`'s `BrandCard` shrinks the shop's
logo client-side and stores it as a data URL on the tenant's branding record, and its own docstring
argues deliberately against a file service standing behind it — "the logo was the only file in the
entire product." A catalogue is the opposite case: a shop may photograph dozens of services and
packages, so the real object store this module uses (already wired for backups, never before used
for a product photo) is exactly the infrastructure that one-picture argument said was not yet
earned.

THE KEY, NEVER THE BYTES OR A URL, IS WHAT `Service`/`Package` STORE. `image_key` is an opaque
reference into `ObjectStore`; the console never learns it (`public()` exposes only `has_image`) and
always fetches the photo through the read route below, the same "never leak an internal reference"
discipline `rating_request.py`'s `flow_token` already holds for a different key.
"""
from __future__ import annotations

from dataclasses import dataclass

from app.ports.errors import NotFound
from app.ports.object_store import ObjectStore

#: Meta's own carousel/media rules accept these; a product photo has no reason to be anything else.
ALLOWED_TYPES = {"image/jpeg": "jpg", "image/png": "png", "image/webp": "webp"}

#: THE REVERSE MAP, AND WHY IT EXISTS RATHER THAN `mimetypes.guess_type`. `ObjectStore.get` returns
#: bytes only — no content-type travels with them — so the read side must recover it from the key's
#: own extension somehow. `mimetypes`'s system registry does not reliably know `.webp` across every
#: platform this runs on (found by this module's own test suite: a stored webp came back as
#: `application/octet-stream` on this box), so the extension is mapped back through the SAME fixed
#: table the write side used to produce it — never a platform-dependent guess for a three-value set
#: we already control completely.
_EXT_TO_TYPE = {ext: ctype for ctype, ext in ALLOWED_TYPES.items()}

#: A product photo, not a video — generous for a real phone photo, still a real ceiling.
MAX_BYTES = 5 * 1024 * 1024


class CatalogueImageError(ValueError):
    """A caller-fixable problem with the upload — surfaced as a 422, never a 500."""


@dataclass
class StoredImage:
    key: str
    content_type: str


def _key(tenant: str, kind: str, item_id: str, ext: str) -> str:
    # `validate_key` (object_store/keys.py) accepts `[A-Za-z0-9._-]` segments only — tenant and
    # item ids are already generated by `new_id`/signup, which never produce anything else.
    return f"catalogue/{tenant}/{kind}/{item_id}.{ext}"


async def store_image(store: ObjectStore, *, tenant: str, kind: str, item_id: str,
                      data: bytes, content_type: str, old_key: str = "") -> StoredImage:
    """Validate, write, and return the new key — the caller still has to save it onto the row.

    THE OLD OBJECT IS DELETED AFTER THE NEW ONE IS WRITTEN, NEVER BEFORE. A crash between the two
    writes must leave the row pointing at a photo that still exists — losing the OLD photo on a
    replace that never finished is a smaller loss than a row pointing at nothing.
    """
    ctype = (content_type or "").lower().split(";")[0].strip()
    if ctype not in ALLOWED_TYPES:
        raise CatalogueImageError(
            f"file_type must be one of {sorted(ALLOWED_TYPES)}, got {ctype!r}")
    if not data:
        raise CatalogueImageError("the uploaded file is empty")
    if len(data) > MAX_BYTES:
        raise CatalogueImageError(f"file exceeds {MAX_BYTES} bytes")
    key = _key(tenant, kind, item_id, ALLOWED_TYPES[ctype])
    await store.put(key, data, content_type=ctype)
    if old_key and old_key != key:
        await store.delete(old_key)
    return StoredImage(key=key, content_type=ctype)


async def read_image(store: ObjectStore, key: str) -> tuple[bytes, str]:
    """The bytes and a best-guess content-type, or raises `NotFound` — the route turns that into
    a 404, never a 500 for the ordinary "no photo yet" case."""
    if not key:
        raise NotFound("no image set")
    data = await store.get(key)
    ext = key.rsplit(".", 1)[-1].lower() if "." in key else ""
    ctype = _EXT_TO_TYPE.get(ext, "application/octet-stream")
    return data, ctype
