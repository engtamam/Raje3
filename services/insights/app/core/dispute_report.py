@dataclass(frozen=True)
class RunResult:
    tenant: str
    title: str
    sources: list[str]
    items: list[ReportItem]
    errors: list[str]


def resolve_tenant(peers: PeerCaller, urls: _Urls, phone: str) -> str:
    try:
        out = peers.post(urls.operations, urls.tenant_by_phone_path, {"phone": phone})
    except PeerCallFailed as exc:
        raise SourceUnavailable(f"تعذّر تحديد المنشأة: {exc}") from exc
    if not out.get("found"):
        raise SourceUnavailable("لا توجد منشأة مسجَّلة بهذا الرقم كمالك.")
    tenant = str(out.get("tenant") or "")
    if not tenant:
        raise SourceUnavailable("المنشأة موجودة لكن تعذّر تحديد معرّفها — لا يمكن المتابعة.")
    return tenant


def run_scenario(peers: PeerCaller, urls: _Urls, phone: str, scenario: str) -> RunResult:
    """Raises `SourceUnavailable` (unknown scenario, or identity resolution failed) — the
    caller's route turns that into a 400/404, same discipline as every other admin action."""
    cfg = SCENARIOS.get(scenario)
    if cfg is None:
        raise SourceUnavailable(
            f"سيناريو غير معروف: {scenario} — المتاح حالياً: {', '.join(sorted(SCENARIOS))}")

    tenant = resolve_tenant(peers, urls, phone)

    all_items: list[ReportItem] = []
    errors: list[str] = []
    for name in cfg["sources"]:
        try:
            all_items.extend(SOURCES[name](peers, urls, tenant))
        except PeerCallFailed as exc:
            errors.append(f"{name}: تعذّر الوصول — {exc}")
        except Exception as exc:                                       # noqa: BLE001
            errors.append(f"{name}: خطأ غير متوقع — {exc}")

    all_items.sort(key=lambda i: (i.ts is None, i.ts or 0))
    return RunResult(tenant=tenant, title=cfg["title"], sources=list(cfg["sources"]),
                     items=all_items, errors=errors)
