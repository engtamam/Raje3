"""The dispute-defense report — a structured record of one ESTABLISHMENT's own history (never a
customer's), for defending Raje3 when a shop files a complaint or threatens legal action.

MOVED HERE FROM A CLAUDE-SIDE TOOL, DELIBERATELY. The first working version of this lived in
ops-mcp (a Claude-only tool) — proven end to end, all 7 dispute scenarios wired, before this
port. That tool now stays registered as an EMERGENCY FALLBACK ONLY (if this service or the
console is down) — the real path is this module, reached through the admin console like any
other admin action, so anyone on the team can generate one, not only through Claude.

SAME SMALL FRAMEWORK AS THE ORIGINAL:
  SOURCES     one function per data area: `(peers, tenant) -> list[ReportItem]`.
  SCENARIOS   a dispute TYPE is a plain config entry — a title plus which SOURCES it pulls.
  the caller  resolves the owner's phone to a tenant id, then runs the scenario's sources, each
              failing independently — one peer being down never blanks the whole report.

ALL 7 SOURCES / ALL 7 SCENARIOS ARE WIRED (2026-09-04). `legal` needed an internal-tier compliance
route that did not exist yet (only user-tier `/api/v1/compliance/legal*` did, and this service
cannot mint a signed JWT itself the way the ops-mcp workaround did — only identity-service holds
that key). base-services_de added the internal-token twins in v0.18.11; `_fetch_legal` calls them
directly, no workaround needed. `acceptance` is the newest source: `legal` answers "what did the
document say and when did it change" — a real dispute needs "did THIS shop's owner actually
accept it, and when", which is a different question with a different answer (compliance's
append-only ConsentProof trail, resolved through identity-service's member directory).

ALSO FOUND LIVE, SAME DAY: `backup_coverage` and `legal` had been silently broken since they were
built — `deploy/services/insights.values.yaml` never set BACKUP_SERVICE_URL or
COMPLIANCE_SERVICE_URL, so every call from either source failed and (by this module's own
per-source isolation) the report just always showed those two sections as unavailable, with
nothing that looked like an error. Fixed in the same values.yaml change that adds
IDENTITY_SERVICE_URL for `acceptance`.
"""
from __future__ import annotations

import time
import urllib.parse
from dataclasses import dataclass, field
from typing import Any, Callable, Protocol


@dataclass(frozen=True)
class ReportItem:
    ts: int | None
    source: str
    label: str
    raw: dict[str, Any] = field(default_factory=dict)


class SourceUnavailable(Exception):
    """Identity resolution failed — caught by the caller, distinct from a per-source failure."""


class PeerCaller(Protocol):
    """The one seam a source needs — implemented by `HttpPeerCaller` in production and a fake in
    tests. Deliberately narrower than insights' own `Peers` port (core/ports.py): that port is
    shaped for the dashboard's existing needs (visits, catalogue, scope), and bolting six new
    unrelated methods onto it would widen a contract every dashboard test also depends on."""

    def get(self, base_url: str, path: str, query: dict[str, Any] | None = None) -> dict[str, Any]: ...
    def post(self, base_url: str, path: str, body: dict[str, Any]) -> dict[str, Any]: ...


class PeerCallFailed(Exception):
    """A source's own peer call failed — caught per-source, never left to blank the report."""


Source = Callable[[PeerCaller, "_Urls", str], list[ReportItem]]


@dataclass(frozen=True)
class _Urls:
    """Just the base URLs + paths a source needs, read once from settings — so a source function
    never imports `app.config` itself and stays trivially testable with a fake `_Urls`."""
    operations: str
    billing: str
    backup: str
    audit: str
    reminders: str
    compliance: str
    tenant_by_phone_path: str
    branches_full_path: str
    operators_full_path: str
    subscriptions_path: str
    invoices_path: str
    tenant_coverage_path: str
    audit_query_path: str
    evidence_path: str
    legal_list_path: str
    legal_history_path: str
    identity: str
    tenancy_members_path: str
    consent_history_path: str


def _redact_dict(d: dict[str, Any]) -> dict[str, Any]:
    # A LIGHTER TOUCH THAN ops-mcp's redact(). This report is generated BY an admin, FOR an
    # admin/legal use, inside our own trust boundary — unlike ops-mcp's tool, whose output can
    # reach a model. Kept as a real function (not a no-op) so a future tightening has one place
    # to change: today it only strips anything that looks like a bearer/API-key assignment.
    import re
    _SECRET_RE = re.compile(r"(?i)(token|secret|password|api[_-]?key)\s*[:=]\s*\S+")
    return {k: (_SECRET_RE.sub(r"\1: [محجوب]", v) if isinstance(v, str) else v) for k, v in d.items()}


def _fmt_ts(ts: int | None) -> str:
    import datetime as dt
    if not ts:
        return "؟"
    return dt.datetime.fromtimestamp(ts, dt.timezone(dt.timedelta(hours=3))).strftime("%Y-%m-%d %H:%M")


def _parse_iso_ts(value: str) -> int | None:
    import datetime as dt
    if not value:
        return None
    try:
        return int(dt.datetime.fromisoformat(str(value).replace("Z", "+00:00")).timestamp())
    except ValueError:
        return None


# ── sources — ONE ENTRY PER DATA AREA ─────────────────────────────────────────────────────────

def _fetch_backup_coverage(peers: PeerCaller, urls: _Urls, tenant: str) -> list[ReportItem]:
    out = peers.get(urls.backup, urls.tenant_coverage_path, {"tenant": tenant})
    if not out.get("run"):
        return [ReportItem(ts=None, source="backup", label="لا يوجد سجل نسخ احتياطي متاح للفحص",
                           raw=_redact_dict(out))]
    covered, fully, incomplete = bool(out.get("covered")), bool(out.get("fully_verified")), bool(out.get("run_incomplete"))
    label = f"نسخة احتياطية (تشغيلة {out.get('run', '؟')}, {_fmt_ts(int(out.get('started_at') or 0) or None)}): "
    if not covered:
        label += "لا يوجد دليل تغطية لهذا المحل بهذي التشغيلة"
    elif fully:
        label += f"مُغطّى ومُتحقَّق منه فعلياً بواسطة: {', '.join(out.get('verified_by') or [])}"
    else:
        label += (f"مُغطّى، لكن غير مُتحقَّق منه بالكامل — "
                  f"مُتحقَّق: {', '.join(out.get('verified_by') or []) or 'لا شيء'}, "
                  f"غير مُتحقَّق: {', '.join(out.get('unverified_by') or [])}")
    if incomplete:
        label += " — تنبيه: هذي التشغيلة نفسها لم تكتمل"
    return [ReportItem(ts=int(out.get("started_at") or 0) or None, source="backup", label=label,
                       raw=_redact_dict(out))]


_INVOICE_STATUS_AR = {"paid": "مدفوعة", "void": "أُبطلت"}


def _fetch_billing(peers: PeerCaller, urls: _Urls, tenant: str) -> list[ReportItem]:
    items: list[ReportItem] = []
    subs_out = peers.get(urls.billing, urls.subscriptions_path, {"tenant": tenant})
    for s in subs_out.get("subscriptions") or []:
        items.append(ReportItem(
            ts=int(s.get("current_period_end") or 0) or None, source="billing",
            label=f"اشتراك — الخطة: {s.get('plan_id', '؟')} — الحالة: {s.get('status', '؟')}",
            raw=_redact_dict(s)))

    for status in ("paid", "void"):
        inv_out = peers.get(urls.billing, urls.invoices_path, {"tenant": tenant, "status": status})
        status_ar = _INVOICE_STATUS_AR.get(status, status)
        for inv in inv_out.get("invoices") or []:
            amount = int(inv.get("amount_minor") or 0) / 100
            label = f"فاتورة ({status_ar}) — {amount:.2f} {inv.get('currency', '')}"
            refunded = int(inv.get("refunded_minor") or 0)
            if refunded:
                label += f" — مُسترجَع: {refunded / 100:.2f}"
            if inv.get("voided_at"):
                label += f" — أُبطلت بتاريخ: {inv['voided_at']}"
            if inv.get("paid_sequence") == 1:
                label += " — أول دفعة لهذه المنشأة"
            ts_raw = inv.get("voided_at") or inv.get("paid_at") or ""
            items.append(ReportItem(ts=_parse_iso_ts(ts_raw), source="billing", label=label,
                                    raw=_redact_dict(inv)))
    return items


def _fetch_staff(peers: PeerCaller, urls: _Urls, tenant: str) -> list[ReportItem]:
    items: list[ReportItem] = []
    br_out = peers.post(urls.operations, urls.branches_full_path, {"tenant": tenant})
    for b in br_out.get("branches") or []:
        state = "مُغلق" if b.get("closed_at") else "مفتوح"
        items.append(ReportItem(ts=int(b.get("closed_at") or b.get("created") or 0) or None,
                                source="staff", label=f"فرع: {b.get('name', '؟')} — الحالة: {state}",
                                raw=_redact_dict(b)))

    op_out = peers.post(urls.operations, urls.operators_full_path, {"tenant": tenant})
    for o in op_out.get("operators") or []:
        state = "نشِط" if o.get("active") else "مُوقَف"
        scope = "كل الفروع" if o.get("visible_all") else (o.get("branch_id") or "غير محدَّد")
        items.append(ReportItem(
            ts=int(o.get("created") or 0) or None, source="staff",
            label=f"موظف: {o.get('name', '؟')} — الدور: {o.get('role', '؟')} — {state} — نطاقه: {scope}",
            raw=_redact_dict(o)))
    return items


def _fetch_audit(peers: PeerCaller, urls: _Urls, tenant: str) -> list[ReportItem]:
    out = peers.get(urls.audit, urls.audit_query_path, {"tenant": tenant, "limit": 200})
    items = []
    for ev in out.get("events") or []:
        actor = str(ev.get("actor") or "") or "النظام"
        action = str(ev.get("action") or "؟")
        label = f"تدقيق — {action} — بواسطة: {actor} — على: {ev.get('resource', '؟')}"
        items.append(ReportItem(ts=int(ev.get("at") or ev.get("created_at") or 0) or None,
                                source="audit", label=label, raw=_redact_dict(ev)))
    return items


def _fetch_marketing_evidence(peers: PeerCaller, urls: _Urls, tenant: str) -> list[ReportItem]:
    out = peers.post(urls.reminders, urls.evidence_path, {"tenant": tenant, "since": 0, "until": 0})
    items: list[ReportItem] = []

    consent = out.get("consent") or {}
    for r in consent.get("records") or []:
        state_ar = {"granted": "مُنحت", "withdrawn": "سُحبت"}.get(r.get("state"), r.get("state", "؟"))
        items.append(ReportItem(
            ts=int(r.get("at") or 0) or None, source="marketing",
            label=f"موافقة تسويقية {state_ar} — نسخة النص: {r.get('statement_version', '؟')} — بواسطة: {r.get('actor', '؟')}",
            raw=_redact_dict(r)))
    if consent.get("truncated"):
        items.append(ReportItem(ts=None, source="marketing",
                                label="⚠ سجل الموافقات أكبر من الحد الأقصى المقروء", raw={}))

    messages = out.get("messages") or {}
    for r in messages.get("records") or []:
        outcome_ar = {"sent": "أُرسلت", "suppressed": "أُوقفت"}.get(r.get("outcome"), r.get("outcome", "؟"))
        label = f"رسالة ({r.get('cls', '؟')}) {outcome_ar} — القالب: {r.get('template_name', '؟')}"
        if r.get("outcome") == "suppressed" and r.get("reason"):
            label += f" — السبب: {r['reason']}"
        items.append(ReportItem(ts=int(r.get("at") or 0) or None, source="marketing", label=label,
                                raw=_redact_dict(r)))
    if messages.get("truncated"):
        items.append(ReportItem(ts=None, source="marketing",
                                label="⚠ سجل الرسائل أكبر من الحد الأقصى المقروء", raw={}))
    return items


def _fetch_legal(peers: PeerCaller, urls: _Urls, tenant: str) -> list[ReportItem]:
    """compliance-service's v0.18.11 internal-token twins — `/internal/compliance/legal` (list)
    + `/legal/{doc_id}/history`. The direct answer to "what did the contract actually say, and
    when": every version ever published, newest first, each with its own publish date."""
    items: list[ReportItem] = []
    docs_out = peers.get(urls.compliance, urls.legal_list_path, {"tenant": tenant})
    for doc in docs_out.get("documents") or []:
        doc_id = str(doc.get("doc_id") or "")
        if not doc_id:
            continue
        hist_path = urls.legal_history_path.format(doc_id=doc_id)
        hist_out = peers.get(urls.compliance, hist_path, {"tenant": tenant})
        for v in hist_out.get("versions") or []:
            status = str(v.get("status") or "")
            status_ar = "منشورة" if status == "published" else ("مسوّدة" if status == "draft" else status)
            req = " (تتطلب موافقة العميل)" if v.get("requires_acceptance") else ""
            label = f"مستند قانوني «{doc_id}» — نسخة {v.get('version', '؟')} — {status_ar}{req}"
            items.append(ReportItem(ts=int(v.get("published_at") or 0) or None, source="legal",
                                    label=label, raw=_redact_dict(v)))
    return items


def _fetch_acceptance(peers: PeerCaller, urls: _Urls, tenant: str) -> list[ReportItem]:
    """WHAT `legal` ABOVE CANNOT ANSWER: not what a document said, but whether THIS shop's own
    owner actually accepted it, and when. `legal` lists publications; this lists proof.

    Two hops, both internal-token: identity-service's member directory finds the owner's
    person_id from the tenant (the `subject` every acceptance was recorded under — see
    compliance's own legal_gate.py: accepting IS a consent grant for purpose "legal:{doc_id}"),
    then compliance's consent-history returns that person's append-only proof records — each one
    grant or withdrawal, the exact notice_version, who/where it happened, and when. This is the
    append-only ConsentProof trail (models.py), not the mutable current-consent row, precisely
    because a dispute needs "what happened", never "what is true right now"."""
    items: list[ReportItem] = []
    members_out = peers.get(urls.identity, urls.tenancy_members_path, {"tenant": tenant})
    members = members_out.get("members") or []
    owner = next((m for m in members if "owner" in (m.get("roles") or [])), None) \
        or (members[0] if members else None)
    if not owner or not owner.get("person_id"):
        return items
    hist_out = peers.get(urls.compliance, urls.consent_history_path,
                         {"tenant": tenant, "subject": owner["person_id"]})
    for p in hist_out.get("proofs") or []:
        purpose = str(p.get("purpose") or "")
        if not purpose.startswith("legal:"):
            continue
        doc_id = purpose.split(":", 1)[1]
        action_ar = {"granted": "وافق على", "withdrawn": "سحب موافقته على"}.get(
            p.get("action"), str(p.get("action") or "؟"))
        label = (f"{action_ar} مستند «{doc_id}» — نسخة {p.get('notice_version', '؟')}"
                f" — من IP {p.get('ip', '؟')}" if p.get("ip") else
                f"{action_ar} مستند «{doc_id}» — نسخة {p.get('notice_version', '؟')}")
        items.append(ReportItem(ts=int(p.get("at") or 0) or None, source="acceptance",
                                label=label, raw=_redact_dict(p)))
    return items


SOURCES: dict[str, Source] = {
    "backup_coverage": _fetch_backup_coverage,
    "billing": _fetch_billing,
    "staff": _fetch_staff,
    "audit": _fetch_audit,
    "marketing_evidence": _fetch_marketing_evidence,
    "legal": _fetch_legal,
    "acceptance": _fetch_acceptance,
}


